#!/usr/bin/env python3
"""Refresh bundled includes and coverage from an explicitly chosen source set.

This intentionally writes only this collection's reference snapshot and
manifest. It never edits the source includes or changes project configuration.
All source files are read and parsed before any destination file is replaced.
New or removed includes require an explicit ownership-map edit first.
"""

from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import sys

sys.dont_write_bytecode = True
import api_catalog


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--include-dir", required=True, help="Directory containing the complete include corpus")
    args = parser.parse_args()
    source_dir = Path(args.include_dir).expanduser().resolve()
    target_dir = api_catalog.SNAPSHOT_DIR.resolve()
    if source_dir == target_dir:
        raise ValueError("Choose the upstream include directory, not the bundled snapshot itself")
    manifest = api_catalog.load_manifest()
    owners = api_catalog.ownership(manifest)
    actual = {path.name for path in source_dir.glob("*.inc")}
    expected = set(owners)
    if actual != expected:
        raise ValueError(f"Update the ownership map before refreshing. Missing: {sorted(expected - actual)}; unmapped: {sorted(actual - expected)}")
    duplicate_names = [name for name, count in Counter(name for names in manifest["owners"].values() for name in names).items() if count != 1]
    if duplicate_names:
        raise ValueError(f"Duplicate include ownership: {duplicate_names}")

    staged: dict[str, bytes] = {}
    metadata = {}
    for name in sorted(expected):
        path = (source_dir / name).resolve()
        if path.parent != source_dir:
            raise ValueError(f"Include resolves outside the chosen source directory: {name}")
        payload = path.read_bytes()
        text = payload.decode("utf-8-sig", errors="replace")
        try:
            symbols = api_catalog.parse_include(name, text)
        except ValueError as error:
            raise ValueError(f"{name}: {error}") from error
        staged[name] = payload
        metadata[name] = {
            "sha256": hashlib.sha256(payload).hexdigest(),
            "bytes": len(payload), "lines": len(text.splitlines()),
            "symbol_declarations": len(symbols),
            "kinds": dict(sorted(Counter(symbol.kind for symbol in symbols).items())),
            "dependencies": re.findall(r"(?m)^\s*#(?:try)?include\s+[<\"]([^>\"]+)[>\"]", text),
            "module_pragmas": sorted(set(re.findall(r"(?m)^\s*#pragma\s+(?:reqlib|loadlib|library)\s+(\w+)", text))),
        }

    version_text = staged["amxmodx_version.inc"].decode("utf-8-sig", errors="replace")
    reapi_text = staged["reapi_version.inc"].decode("utf-8-sig", errors="replace")
    amxx_version = re.search(r'AMXX_VERSION_STR\[\]\s*=\s*"([^"]+)"', version_text)
    changeset = re.search(r'#define\s+AMXX_VERSION_CSET\s+"([^"]+)"', version_text)
    def reapi_define(name: str) -> str:
        match = re.search(r"#define\s+" + re.escape(name) + r"\s+(\d+)", reapi_text)
        return match.group(1) if match else "unknown"
    manifest["versions"] = {
        "amxmodx": amxx_version.group(1) if amxx_version else "unknown",
        "amxmodx_changeset": changeset.group(1) if changeset else "unknown",
        "reapi": f"{reapi_define('REAPI_VERSION_MAJOR')}.{reapi_define('REAPI_VERSION_MINOR')} (REAPI_VERSION={reapi_define('REAPI_VERSION')})",
    }
    # The date describes the originally supplied baseline. Hashes describe the
    # actual current snapshot; no inferred release date is assigned.
    manifest["files"] = metadata
    target_dir.mkdir(parents=True, exist_ok=True)
    for name, payload in staged.items():
        target = target_dir / name
        if target.resolve().parent != target_dir:
            raise ValueError(f"Invalid destination include name: {name}")
        temporary = target.with_suffix(".inc.tmp")
        temporary.write_bytes(payload)
        temporary.replace(target)
    temporary_manifest = api_catalog.MANIFEST_PATH.with_suffix(".json.tmp")
    temporary_manifest.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    temporary_manifest.replace(api_catalog.MANIFEST_PATH)
    report = [
        "# Include coverage", "",
        "Generated by `scripts/refresh_snapshot.py`. Every include has one primary owner; other skills may use it as a dependency.", "",
        "The raw include files remain the authority for exact signatures, comments, hook parameters and constants. The lexical index retains conditional branches and does not evaluate macro expressions.", "",
        f"Snapshot: AMX Mod X {manifest['versions']['amxmodx']}; ReAPI {manifest['versions']['reapi']}.", "",
        "| Include | Primary skill | Lines | Native / forward / stock | Symbol declarations |",
        "| --- | --- | ---: | ---: | ---: |",
    ]
    for name, data in metadata.items():
        skill = owners[name]
        kinds = data["kinds"]
        native_forward_stock = " / ".join(str(kinds.get(kind, 0)) for kind in ("native", "forward", "stock"))
        report.append(f"| [{name}](includes/{name}) | [{skill}](../../{skill}/SKILL.md) | {data['lines']} | {native_forward_stock} | {data['symbol_declarations']} |")
    report.extend(["", f"Total: {len(metadata)} includes, {sum(data['lines'] for data in metadata.values())} lines, {sum(data['symbol_declarations'] for data in metadata.values())} lexical symbol declarations.", ""])
    (api_catalog.SKILL_DIR / "references" / "include-coverage.md").write_text("\n".join(report), encoding="utf-8")
    print(f"Refreshed {len(staged)} includes; {sum(data['symbol_declarations'] for data in metadata.values())} lexical symbol declarations. Source directory unchanged.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, KeyError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        sys.exit(2)
